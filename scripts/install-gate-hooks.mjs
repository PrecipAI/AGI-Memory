// 安装 git hooks 到 .git/hooks/，让 gate-runtime 在 git commit 时自动触发
//
// 用法:
//   node scripts/install-gate-hooks.mjs           # 安装 pre-commit
//   node scripts/install-gate-hooks.mjs --force    # 强制覆盖已存在的 hook
//   node scripts/install-gate-hooks.mjs --uninstall # 移除 gate-runtime 的 hook
//
// 安装后 git commit 会自动执行 .trae/gates/ 中 mount_points 包含 pre_commit 的 hook
// REJECT 时 commit 会被阻断（exit 1）

import { existsSync, writeFileSync, readFileSync, unlinkSync, chmodSync } from "node:fs";
import path from "node:path";

const args = process.argv.slice(2);
const FORCE = args.includes("--force");
const UNINSTALL = args.includes("--uninstall");

const REPO_ROOT = path.resolve(import.meta.dirname, "..");
const GIT_HOOKS_DIR = path.join(REPO_ROOT, ".git", "hooks");
const PRE_COMMIT_PATH = path.join(GIT_HOOKS_DIR, "pre-commit");

const MARKER_BEGIN = "# >>> gate-runtime (auto-installed) >>>";
const MARKER_END = "# <<< gate-runtime (auto-installed) <<<";

function buildPreCommitScript() {
  const runtimePath = path.relative(GIT_HOOKS_DIR, path.join(REPO_ROOT, "scripts", "gate-runtime.mjs"));
  // 用 node 绝对路径 + runtime 绝对路径，避免 cwd 问题
  const runtimeAbs = path.join(REPO_ROOT, "scripts", "gate-runtime.mjs").replace(/\\/g, "/");
  return `#!/bin/sh
# Auto-generated by scripts/install-gate-hooks.mjs
# 调用 gate-runtime 执行 .trae/gates/*.hook.ts 中 mount_points 含 pre_commit 的门控检查
${MARKER_BEGIN}
node "${runtimeAbs}" --mount-point=pre_commit --task-type=coding --operation=commit
exit_code=$?
if [ $exit_code -eq 1 ]; then
  echo ""
  echo "🛑 Gate runtime 阻断了 commit（REJECT）"
  echo "   修复上述问题后重试，或 git commit --no-verify 跳过（不推荐）"
  exit 1
fi
# exit_code=0 (PASS) 或 2 (runtime 自身出错) 都放行
exit 0
${MARKER_END}
`;
}

function ensureHooksDir() {
  if (!existsSync(GIT_HOOKS_DIR)) {
    // .git/hooks 一般 git init 时就建好了，到不了这里
    import("node:fs").then(({ mkdirSync }) => mkdirSync(GIT_HOOKS_DIR, { recursive: true }));
  }
}

function install() {
  ensureHooksDir();

  // 已存在内容处理
  let existing = "";
  if (existsSync(PRE_COMMIT_PATH)) {
    existing = readFileSync(PRE_COMMIT_PATH, "utf8");

    // 已安装过 → 幂等
    if (existing.includes(MARKER_BEGIN)) {
      if (!FORCE) {
        console.log("[install-gate-hooks] pre-commit 已存在 gate-runtime 段，跳过（用 --force 强制覆盖）");
        return;
      }
      // 移除旧段
      const re = new RegExp(`${MARKER_BEGIN}[\\s\\S]*?${MARKER_END}\\n?`, "g");
      existing = existing.replace(re, "");
    }
  }

  const newContent = (existing + "\n" + buildPreCommitScript()).replace(/^\n+/, "");
  writeFileSync(PRE_COMMIT_PATH, newContent, "utf8");

  // Windows 也要 chmod，git for windows 会读
  try { chmodSync(PRE_COMMIT_PATH, 0o755); } catch {}

  console.log(`[install-gate-hooks] ✅ 已安装 pre-commit → ${path.relative(REPO_ROOT, PRE_COMMIT_PATH)}`);
  console.log(`[install-gate-hooks] runtime: scripts/gate-runtime.mjs`);
  console.log(`[install-gate-hooks] 现在每次 git commit 都会自动执行 .trae/gates/ 中 mount_points 含 pre_commit 的 hook`);
}

function uninstall() {
  if (!existsSync(PRE_COMMIT_PATH)) {
    console.log("[install-gate-hooks] pre-commit 不存在，无需卸载");
    return;
  }
  const existing = readFileSync(PRE_COMMIT_PATH, "utf8");
  if (!existing.includes(MARKER_BEGIN)) {
    console.log("[install-gate-hooks] pre-commit 中无 gate-runtime 段，无需卸载");
    return;
  }
  const re = new RegExp(`${MARKER_BEGIN}[\\s\\S]*?${MARKER_END}\\n?`, "g");
  const cleaned = existing.replace(re, "").trim();
  if (cleaned) {
    writeFileSync(PRE_COMMIT_PATH, cleaned + "\n", "utf8");
    console.log("[install-gate-hooks] ✅ 已移除 gate-runtime 段，保留其他 hook 内容");
  } else {
    unlinkSync(PRE_COMMIT_PATH);
    console.log("[install-gate-hooks] ✅ 已删除 pre-commit（无其他 hook 内容）");
  }
}

if (UNINSTALL) {
  uninstall();
} else {
  install();
}
