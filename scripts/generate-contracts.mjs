import fs from "node:fs/promises";
import path from "node:path";
import openapiTS, { astToString } from "openapi-typescript";
import YAML from "yaml";

const repoRoot = process.cwd();
const openApiPath = path.join(repoRoot, "contracts", "internal", "internal-api-v1.openapi.yaml");
const stateMachinePath = path.join(repoRoot, "contracts", "enums", "state-machines.v1.json");
const outDir = path.join(repoRoot, "libs", "contracts", "src", "generated");

await fs.mkdir(outDir, { recursive: true });

const openApiDocument = YAML.parse(await fs.readFile(openApiPath, "utf8"));
const openApiAst = await openapiTS(openApiDocument);
const openApiTypes = astToString(openApiAst);
await fs.writeFile(
  path.join(outDir, "internal-api.ts"),
  `/* eslint-disable */\n/* auto-generated by scripts/generate-contracts.mjs */\n${openApiTypes}`,
  "utf8"
);

const stateMachineJson = JSON.parse(await fs.readFile(stateMachinePath, "utf8"));
const stateMachineTs = `/* eslint-disable */
/* auto-generated by scripts/generate-contracts.mjs */
export const eventNaming = ${JSON.stringify(stateMachineJson.event_naming)} as const;
export const stateMachineEnums = ${JSON.stringify(stateMachineJson.enums, null, 2)} as const;
export const stateMachines = ${JSON.stringify(stateMachineJson.state_machines, null, 2)} as const;

export type TaskRequestStatus = typeof stateMachineEnums.task_request_status[number];
export type TaskPlanStatus = typeof stateMachineEnums.task_plan_status[number];
export type TaskStepStatus = typeof stateMachineEnums.task_step_status[number];
export type CleanupStatus = typeof stateMachineEnums.cleanup_status[number];
export type DependencyStatus = typeof stateMachineEnums.dependency_status[number];
export type StreamState = typeof stateMachineEnums.stream_state[number];
export type TaskRunStatus = typeof stateMachineEnums.task_run_status[number];
export type MemoryCandidateStatus = typeof stateMachineEnums.memory_candidate_status[number];
export type FingerprintStatus = typeof stateMachineEnums.fingerprint_status[number];
`;

await fs.writeFile(path.join(outDir, "state-machines.ts"), stateMachineTs, "utf8");
console.log("generated contracts -> libs/contracts/src/generated");
