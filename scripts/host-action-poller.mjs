import fs from "node:fs/promises";
import path from "node:path";

const MEMORY_SERVICE_URL = process.env.MEMORY_SERVICE_URL || "http://127.0.0.1:3101";
const GATES_DIR = process.env.GATES_DIR || path.join(process.cwd(), ".trae", "gates");
const PROJECT_ID = process.env.PROJECT_ID || null;
const GLOBAL_SKILLS_DIR = process.env.GLOBAL_SKILLS_DIR || path.join(process.env.USERPROFILE || process.env.HOME || process.cwd(), ".trae-cn", "skills");
const PROJECT_SKILLS_DIR = process.env.PROJECT_SKILLS_DIR || path.join(process.cwd(), ".trae", "skills");

function isGlobalSkill(record) {
  return (
    ["global", "team"].includes(record.origin_scope) &&
    ["global_reusable", "team_reusable"].includes(record.availability_scope)
  );
}

function resolveSkillDir(record) {
  const skillKey = record.skill_key || "unnamed";
  if (isGlobalSkill(record)) {
    return path.join(GLOBAL_SKILLS_DIR, skillKey);
  }
  return path.join(PROJECT_SKILLS_DIR, skillKey);
}

async function fetchPending() {
  const url = new URL(`${MEMORY_SERVICE_URL}/internal/host-actions/pending`);
  url.searchParams.set("object_type", "all");
  if (PROJECT_ID) url.searchParams.set("project_id", PROJECT_ID);

  const res = await fetch(url, {
    headers: {
      "x-tenant-id": "tenant-local",
      "x-scope": "memory.validation"
    }
  });
  if (!res.ok) {
    throw new Error(`fetch pending failed: ${res.status} ${await res.text()}`);
  }
  const data = await res.json();
  return data.items || [];
}

async function markStatus(objectType, objectId, status, error) {
  const body = { status };
  if (error) body.error = error;
  const res = await fetch(`${MEMORY_SERVICE_URL}/internal/host-actions/${objectType}/${objectId}/status`, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "x-tenant-id": "tenant-local",
      "x-scope": "memory.validation"
    },
    body: JSON.stringify(body)
  });
  if (!res.ok) {
    throw new Error(`mark status failed: ${res.status} ${await res.text()}`);
  }
}

function buildSkillMarkdown(item) {
  const record = item.invoke_skill?.payload?.skill_record || {};
  const procedure = record.procedure_payload || {};
  const executionSteps = procedure.execution_steps || procedure.steps || [];
  const scenarios = record.applicable_scenarios || [];
  const nonScenarios = record.non_applicable_scenarios || [];
  const isGlobal = isGlobalSkill(record);

  let body = `---
name: ${record.title || item.key}
description: ${record.description || ""}
---

# ${record.title || item.key}

## 描述

${record.description || ""}

`;

  if (scenarios.length > 0) {
    body += `## 使用场景\n\n`;
    for (const s of scenarios) {
      body += `- ${s}\n`;
    }
    body += `\n`;
  }

  if (nonScenarios.length > 0) {
    body += `## 不适用场景\n\n`;
    for (const s of nonScenarios) {
      body += `- ${s}\n`;
    }
    body += `\n`;
  }

  body += `## 指令\n\n`;
  if (executionSteps.length > 0) {
    for (let i = 0; i < executionSteps.length; i++) {
      body += `${i + 1}. ${executionSteps[i]}\n`;
    }
  } else {
    body += "_暂无执行步骤。_\n";
  }

  body += `\n## 触发条件\n\n\`\`\`json\n${JSON.stringify(record.trigger_conditions || {}, null, 2)}\n\`\`\`\n\n`;

  if (!isGlobal) {
    body += `## 作用域\n\n- Origin scope: ${record.origin_scope || "session"}\n- Availability scope: ${record.availability_scope || "session_only"}\n- Project: ${record.scope || "-"}\n`;
  } else {
    body += `## 作用域\n\n- 全局技能（${record.origin_scope} / ${record.availability_scope}）\n- 严禁在任何描述中引用项目特定名称、角色名、文件路径或故事设定。\n`;
  }

  return body;
}

function buildHookFile(item) {
  const payload = item.invoke_skill?.payload || {};
  const ruleKey = payload.rule_key || "unknown";
  const safeKey = ruleKey.toLowerCase().replace(/[^a-z0-9_]/g, "_");

  return `// AUTO-GENERATED by GateMaster — DO NOT EDIT MANUALLY
// Rule: ${payload.title || ruleKey}
// Rule Key: ${ruleKey}
// Enforcement: ${payload.enforcement_level || "must"}
// Scope: ${payload.origin_scope || "session"} / ${payload.availability_scope || "session_only"}

import type { GateContext, HookResult, RuleHook } from "./types";

export const hook: RuleHook = {
  id: "hook_${safeKey}",
  rule_id: "${payload.rule_id || ""}",
  rule_key: "${ruleKey}",
  mount_points: ["before_task_complete"],

  shouldRun(context: GateContext): boolean {
    // TODO: translate trigger_conditions into precise matching logic
    return true;
  },

  async run(context: GateContext): Promise<HookResult> {
    // TODO: translate statement into enforcement logic
    // Rule statement: ${(payload.statement || "").replace(/`/g, "\\`")}
    return { action: "PASS" };
  }
};
`;
}

async function processSkill(item) {
  const record = item.invoke_skill?.payload?.skill_record || {};
  const skillDir = resolveSkillDir(record);
  const filePath = path.join(skillDir, "SKILL.md");
  await fs.mkdir(skillDir, { recursive: true });
  await fs.writeFile(filePath, buildSkillMarkdown(item), "utf8");
  console.log(`[skill] wrote ${filePath}`);
  await markStatus("skill", item.id, "generated");
}

async function processRule(item) {
  const ruleKey = item.key;
  const filePath = path.join(GATES_DIR, `${ruleKey}.hook.ts`);
  await fs.mkdir(GATES_DIR, { recursive: true });
  await fs.writeFile(filePath, buildHookFile(item), "utf8");
  console.log(`[rule] wrote ${filePath}`);
  await markStatus("rule", item.id, "generated");
}

async function main() {
  const items = await fetchPending();
  if (items.length === 0) {
    console.log("No pending host actions.");
    return;
  }

  for (const item of items) {
    try {
      if (item.object_type === "skill") {
        await processSkill(item);
      } else if (item.object_type === "rule") {
        await processRule(item);
      } else {
        console.warn("Unknown host action type:", item.object_type);
      }
    } catch (error) {
      console.error(`Failed to process ${item.object_type} ${item.id}:`, error);
      await markStatus(item.object_type, item.id, "failed", String(error));
    }
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
